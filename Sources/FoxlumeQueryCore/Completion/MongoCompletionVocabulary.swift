import Foundation

/// One name the MongoDB completer offers: the public API name, an optional argument hint and a one-line summary.
struct MongoCompletionTerm: Sendable {
    let name: String
    let detail: String?
    let summary: String

    init(_ name: String, _ detail: String? = nil, _ summary: String) {
        self.name = name
        self.detail = detail
        self.summary = summary
    }
}

